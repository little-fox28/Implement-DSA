package Leetcode.medium.AddTwoNumber;

/**
 * Definition for singly-linked list (LeetCode Standard).
 */
public class ListNode {
    public int val;
    public ListNode next;

    public ListNode() {
    }

    public ListNode(int val) {
        this.val = val;
    }

    public ListNode(int val, ListNode next) {
        this.val = val;
        this.next = next;
    }
}
